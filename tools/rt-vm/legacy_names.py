#!/usr/bin/env python3
"""Runtime 2.0 CP11: names the legacy engine may resolve specially, extracted
from the legacy SOURCE (not a hand list).

  legacy_names.py            print the generated src/rt/legacy_names.cpp
  legacy_names.py --check    exit 1 if src/rt/legacy_names.cpp is stale
  legacy_names.py --write    regenerate src/rt/legacy_names.cpp

The compiler refuses (static fallback) any unit that declares a function,
parameter or binding with one of these names, because legacy may dispatch a
built-in, a template function, a method or a metadata binding for it before
(or instead of) the user definition (review findings D4, D5; candidate
language change D-014). The extraction is deliberately broad: refusing a
harmless name only costs coverage, missing one can miscompile.

Sources: every legacy evaluator file (src/Parser*.cpp, src/Ast.cpp,
src/CLI.cpp). Identifier-shaped string literals are collected from these
syntactic contexts:
  1. call_args("NAME", ...)                          native call heads
  2. rfind/find/compare/starts_with("NAME(", ...)    call-prefix tests
  3. VAR == "NAME", "NAME" == VAR, VAR != "NAME"     where VAR is a variable
     holding a callee, function, method, binding or keyword name (DISPATCH_VARS)
  4. brace lists consisting only of string literals  name sets (native_heads,
     reserved_binding_name, the is_* predicate loop, keyword sets, ...)
plus the evaluator's statement keywords and script bindings (KEYWORDS).
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "src", "rt", "legacy_names.cpp")
SOURCES = ["src/Parser*.cpp", "src/Ast.cpp", "src/CLI.cpp"]

ID = r"[A-Za-z_][A-Za-z0-9_]*"
DISPATCH_VARS = (r"name|fn|fname|func|head|callee|pred|ctor|kw|keyword|op_name|"
                 r"expression\.name|e\.left->name|e\.name|call\.name|root_name|target|base_name")
PATTERNS = [
    re.compile(r'call_args\(\s*"(' + ID + r')"'),
    re.compile(r'(?:rfind|find|compare|starts_with)\(\s*(?:0\s*,\s*\d+\s*,\s*)?"(' + ID + r')\('),
    re.compile(r'(?<![A-Za-z0-9_])(?:' + DISPATCH_VARS + r')\s*[!=]=\s*"(' + ID + r')"'),
    re.compile(r'"(' + ID + r')"\s*[!=]=\s*(?:' + DISPATCH_VARS + r')(?![A-Za-z0-9_])'),
]
BRACE_LIST = re.compile(r'\{\s*("(?:[^"\\]|\\.)*"\s*(?:,\s*"(?:[^"\\]|\\.)*"\s*)+)\}')
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')
KEYWORDS = """fn struct enum import export return throw try catch if else while for break continue const immut
true false null this self lambda async await content input script args inject defer""".split()


def strip_comments(text):
    """Remove // and /* */ comments outside string and character literals."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def extract():
    names = set(KEYWORDS)
    for pattern in SOURCES:
        for path in sorted(glob.glob(os.path.join(REPO, pattern))):
            text = strip_comments(open(path, encoding="utf-8", errors="replace").read())
            for regex in PATTERNS:
                names.update(regex.findall(text))
            for match in BRACE_LIST.finditer(text):
                for literal in LITERAL.findall(match.group(1)):
                    if re.fullmatch(ID, literal):
                        names.add(literal)
    return sorted(names)


def render(names):
    lines = ["// GENERATED by tools/rt-vm/legacy_names.py from the legacy evaluator source; do not edit.",
             "// `make test-rt-vm` fails when this file is stale (legacy_names.py --check).",
             '#include "rt/legacy_names.h"', "", "#include <algorithm>", "#include <iterator>", "",
             "// rt-lint: cold-file compile-time name table", "", "namespace nift::rt {", "",
             "namespace {", "",
             "// Sorted (byte order) for binary search; no construction at run time.",
             "constexpr std::string_view kNames[] = {"]
    row = "   "
    for n in sorted(names, key=lambda x: x.encode()):
        item = ' "%s",' % n
        if len(row) + len(item) > 118:
            lines.append(row)
            row = "   "
        row += item
    lines.append(row)
    lines += ["};", "", "} // namespace", "",
              "bool legacy_special_name(std::string_view name) {",
              "    return std::binary_search(std::begin(kNames), std::end(kNames), name);", "}", "",
              "std::size_t legacy_special_name_count() { return std::size(kNames); }", "",
              "} // namespace nift::rt", ""]
    return "\n".join(lines)


def main():
    text = render(extract())
    if "--write" in sys.argv:
        open(OUT, "w").write(text)
        return 0
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("legacy_names: src/rt/legacy_names.cpp is stale; run tools/rt-vm/legacy_names.py --write")
            return 1
        print("legacy_names: %d names, up to date" % text.count('",'))
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
