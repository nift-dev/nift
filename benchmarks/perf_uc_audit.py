#!/usr/bin/env python3
"""Changed-vs-unchanged persistence benchmark (U and C workloads).

U: 10,000 selected pages whose generated bytes are already identical to the
   on-disk output (current compare+touch fast path for C).
C: 10,000 selected pages whose generated bytes genuinely differ from the
   on-disk output (transactional temp+rename for C; direct write for A).

For C the content files are toggled between two states outside the timed
region before every measured build, so every measured iteration really
causes all 10,000 outputs to differ (the first measured build cannot turn
the rest into the unchanged workload).

Protocol: same fixture structure, same compiler, clean binaries, warmups,
20 interleaved measurements, raw samples retained.
"""
import argparse, json, os, pathlib, statistics, shutil, subprocess, tempfile, time

ap = argparse.ArgumentParser()
ap.add_argument("--baseline", required=True)
ap.add_argument("--current", required=True)
ap.add_argument("--workload", choices=["U", "C"], required=True)
ap.add_argument("--pages", type=int, default=10000)
ap.add_argument("--samples", type=int, default=20)
ap.add_argument("--warmup", type=int, default=3)
a = ap.parse_args()


def mk(root: pathlib.Path, pages: int, bang: bool):
    root.mkdir(parents=True)
    for d in (".nift", "content", "templates", "public"):
        (root / d).mkdir()
    (root / ".nift/config.json").write_text(json.dumps({"config": {
        "content-dir": "content/", "content-ext": ".html", "output-dir": "public/",
        "output-ext": ".html", "default-template": "templates/template.html",
        "build-threads": -1, "incremental-mode": "modified", "minify-exts": []}}, separators=(",", ":")))
    (root / ".nift/tracked.json").write_text(json.dumps({"tracked": [
        {"name": f"p{i}", "title": f"P{i}", "template": "templates/template.html"}
        for i in range(pages)]}, separators=(",", ":")))
    (root / "templates/template.html").write_text("@content\n")
    set_content(root, pages, bang)


def set_content(root: pathlib.Path, pages: int, bang: bool):
    marker = "!" if bang else ""
    for i in range(pages):
        (root / "content" / f"p{i}.html").write_text(f"<p>{i}{marker}</p>\n")


def build(nift: str, root: pathlib.Path) -> float:
    start = time.perf_counter()
    p = subprocess.run([nift, "build", "--all"], cwd=root, stdout=subprocess.DEVNULL,
                       stderr=subprocess.PIPE)
    if p.returncode:
        raise SystemExit(p.stderr.decode(errors="replace"))
    return time.perf_counter() - start


def tree(root: pathlib.Path) -> dict:
    out = {}
    for path in sorted((root / "public").rglob("*")):
        if path.is_file():
            out[path.relative_to(root / "public").as_posix()] = path.read_bytes()
    return out


def report(label, samples):
    s = sorted(samples)
    m = statistics.mean(s)
    v = sum((x - m) ** 2 for x in s) / (len(s) - 1)
    print(f"{label}: median={statistics.median(s)*1000:.2f}ms min={s[0]*1000:.2f} "
          f"max={s[-1]*1000:.2f} mean={m*1000:.2f} std={v**0.5*1000:.2f}")
    print(f"  raw: {[f'{x:.4f}' for x in samples]}")


with tempfile.TemporaryDirectory(prefix=f"nift-uc-{a.workload}-") as td:
    td = pathlib.Path(td)
    root = td / "project"
    mk(root, a.pages, bang=False)

    # Correctness: both implementations must produce byte-identical output.
    for name, nift in (("baseline", a.baseline), ("current", a.current)):
        copy = td / f"fix-{name}"
        shutil.copytree(root, copy)
        build(nift, copy)
        print(f"{name} output pages: {len(tree(copy))}")
    same = tree(td / "fix-baseline") == tree(td / "fix-current")
    print(f"output byte-identical: {same}")

    # Seed the on-disk outputs, then measure.
    build(a.baseline, root)
    build(a.current, root)
    base_samples, cur_samples = [], []
    bang = False
    for _ in range(a.warmup):
        if a.workload == "C":
            bang = not bang
            set_content(root, a.pages, bang)
        build(a.baseline, root)
        if a.workload == "C":
            bang = not bang
            set_content(root, a.pages, bang)
        build(a.current, root)
    for _ in range(a.samples):
        if a.workload == "C":
            bang = not bang
            set_content(root, a.pages, bang)
        base_samples.append(build(a.baseline, root))
        if a.workload == "C":
            bang = not bang
            set_content(root, a.pages, bang)
        cur_samples.append(build(a.current, root))

    print(f"--- workload {a.workload} (10k full build, interleaved, {a.samples} samples) ---")
    report("Pre-Embed A", base_samples)
    report("Current C  ", cur_samples)
    bm = statistics.median(base_samples)
    cm = statistics.median(cur_samples)
    print(f"current/baseline median: {cm/bm:.4f}x  delta: {cm-bm:+.4f}s  ({(cm-bm)/bm*100:+.1f}%)")
