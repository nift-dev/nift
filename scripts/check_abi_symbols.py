#!/usr/bin/env python3
"""Tooling checkpoint (component 6): the exported symbol inventory of libnift_c.

    check_abi_symbols.py LIBRARY HEADER INVENTORY [--extra FILE] [--cc CC]
    check_abi_symbols.py --write-map OUT HEADER --extra FILE [--cc CC]

--write-map generates the GNU ld version script of libnift_c.so from the
documented public embedding API: the functions declared in HEADER
(include/nift/c_abi.h, read after the C preprocessor) plus the documented
exceptions in --extra (src/embed/abi-exports-extra.txt), each by exact name
(no wildcard), everything else local.

Compares the library's exported dynamic symbols (`nm -D --defined-only`)
with the intended embedding ABI and fails (exit 1) when
  * any exported symbol is not named nift_* (an internal symbol leaks);
  * any function declared in HEADER (include/nift/c_abi.h, read after the C
    preprocessor) is not exported (the documented interface lost a symbol);
  * the exported set differs from INVENTORY (tests/abi/libnift_c.symbols),
    which is the declared functions plus the documented exceptions listed
    there, in either direction.
"""
import argparse
import re
import subprocess
import sys


def exported(lib):
    out = subprocess.run(["nm", "-D", "--defined-only", lib], check=True, capture_output=True, text=True).stdout
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3:
            syms.add(parts[2].split("@")[0])
    return syms


def declared(header, cc):
    text = subprocess.run([cc, "-E", "-P", "-x", "c", header], check=True, capture_output=True, text=True).stdout
    text = re.sub(r"\s+", " ", text)
    # Drop every braced body (struct/enum definitions), then each remaining
    # top-level declaration that is not a typedef declares at most one
    # function: an identifier directly followed by a parameter list (not a
    # `(*` function-pointer declarator).
    while True:
        stripped = re.sub(r"\{[^{}]*\}", " ", text)
        if stripped == text:
            break
        text = stripped
    names = set()
    for decl in text.split(";"):
        decl = decl.strip()
        if not decl or decl.startswith("typedef"):
            continue
        m = re.search(r"\b(nift_\w+)\s*\((?!\s*\*)", decl)
        if m:
            names.add(m.group(1))
    return names


def extra_symbols(path):
    names = set()
    for line in open(path):
        name = line.split("#", 1)[0].strip()
        if name:
            names.add(name)
    return names


def write_map(out, header, extra, cc):
    names = sorted(declared(header, cc) | extra_symbols(extra))
    with open(out + ".tmp", "w") as f:
        f.write("/* Generated by scripts/check_abi_symbols.py from %s and %s:\n"
                "   the exact exported dynamic symbols of libnift_c.so (Linux, GNU ld). */\n" % (header, extra))
        f.write("{\n  global:\n")
        for n in names:
            f.write("    %s;\n" % n)
        f.write("  local:\n    *;\n};\n")
    import os
    os.replace(out + ".tmp", out)
    print(f"wrote {out}: {len(names)} exported symbols")
    return 0


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--write-map":
        ap = argparse.ArgumentParser()
        ap.add_argument("--write-map", dest="out", required=True)
        ap.add_argument("header")
        ap.add_argument("--extra", required=True)
        ap.add_argument("--cc", default="cc")
        a = ap.parse_args()
        return write_map(a.out, a.header, a.extra, a.cc)
    ap = argparse.ArgumentParser()
    ap.add_argument("library")
    ap.add_argument("header")
    ap.add_argument("inventory")
    ap.add_argument("--extra")
    ap.add_argument("--cc", default="cc")
    a = ap.parse_args()
    have = exported(a.library)
    decl = declared(a.header, a.cc)
    want = {l.strip() for l in open(a.inventory) if l.strip() and not l.startswith("#")}
    fail = False
    leaks = sorted(s for s in have if not s.startswith("nift_"))
    if leaks:
        fail = True
        print(f"FAIL abi-symbols: {len(leaks)} exported symbols are not nift_* (first: {', '.join(leaks[:5])})")
    else:
        print(f"PASS abi-symbols: every exported symbol is nift_* ({len(have)} exported)")
    missing_decl = sorted(decl - have)
    if missing_decl:
        fail = True
        print(f"FAIL abi-symbols: declared in {a.header} but not exported: {', '.join(missing_decl)}")
    else:
        print(f"PASS abi-symbols: all {len(decl)} functions declared in {a.header} are exported")
    undeclared = sorted(want - decl)
    if a.extra and want != decl | extra_symbols(a.extra):
        fail = True
        print(f"FAIL abi-symbols: {a.inventory} != declared functions + {a.extra}")
    if not decl <= want:
        fail = True
        print(f"FAIL abi-symbols: the inventory lacks declared functions: {', '.join(sorted(decl - want))}")
    if have != want:
        fail = True
        print(f"FAIL abi-symbols: exported != inventory; extra {sorted(have - want)} missing {sorted(want - have)}")
    else:
        print(f"PASS abi-symbols: exported set equals {a.inventory} ({len(want)}: {len(decl)} declared"
              f" + {len(undeclared)} documented exception(s): {', '.join(undeclared) or 'none'})")
    return 1 if fail else 0


if __name__ == "__main__":
    sys.exit(main())
