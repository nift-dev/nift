// D-NEXT-refsem #3 (D3): copy() is shallow (v4.2), deepcopy() deep; legacy v4.4+ copies deeply.
inner := map()
inner.set(1, 1)
outer := map()
outer.set("i", inner)
c := copy(outer)
inner.set(2, 2)
x := c.get("i")
print(x.size())
print(same(x, inner))
d := deepcopy(outer)
inner.set(3, 3)
y := d.get("i")
print(y.size())
print(same(c, outer))
